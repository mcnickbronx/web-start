// Отправка заявки — договорённости с бэкендом: пауза ловушки по времени и когда нужен новый токен формы

/**
 * Сколько ещё подождать перед отправкой. Бэкенд считает ботом форму, отправленную быстрее
 * fill_seconds_min из описания формы, и молча кладёт заявку в спам. Человек, вставивший
 * телефон из буфера, может успеть быстрее — ждём за него.
 */
export function fillWaitMs(loadedAt: number, now: number, minMs: number): number {
  return Math.max(0, loadedAt + minMs - now)
}

/**
 * Нужен ли новый токен формы после ошибки отправки — договорённость с бэкендом по коду, не по тексту:
 * 406 (форма устарела, заявка уже отправлена, форма выключена) или не пройдена капча (вопрос сменится).
 * При ошибках полей токен не трогаем — к нему привязаны загруженные файлы.
 */
export function needsNewToken(error: { status: number, fieldMap: Record<string, string> }): boolean {
  return error.status === 406 || 'captcha' in error.fieldMap
}
